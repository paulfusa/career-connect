<script lang="ts">
	import SectionTabs from '$lib/components/SectionTabs.svelte';
	import { enhance } from '$app/forms';
	import OrgLogo from '$lib/components/OrgLogo.svelte';
	import { withPending } from '$lib/forms';
	import { EMPLOYMENT_TYPES, WORK_MODES } from '$lib/profile-options';
	import { errorBox, field, glassPanel, label, primaryButton } from '$lib/ui';
	import type { PageProps } from './$types';

	let { data, form }: PageProps = $props();

	let pending = $state(false);
	const dateFmt = new Intl.DateTimeFormat('en-CA', { dateStyle: 'medium', timeStyle: 'short' });
	const card = `${glassPanel} p-6`;
	const levels = {
		strong: { text: 'Strong match', style: 'bg-emerald-100/80 text-emerald-800 dark:bg-emerald-950/60 dark:text-emerald-300' },
		good: { text: 'Good match', style: 'bg-tide/15 text-tide-deep dark:bg-tide/20 dark:text-[#7dd3df]' },
		partial: { text: 'Partial match', style: 'bg-amber-100/80 text-amber-800 dark:bg-amber-950/60 dark:text-amber-300' }
	};
</script>

<svelte:head><title>Job matches · CareerConnect</title></svelte:head>

<SectionTabs section="jobs" />

<div class="space-y-5">
	<div>
		<h1 class="font-display text-3xl font-semibold tracking-tight">Job matches</h1>
		<p class="mt-2 text-ink/60">AI suggestions from the open postings, based on your profile and resume.</p>
	</div>

	{#if !data.ai.configured}
		<p class={card}>AI features aren’t set up on this server yet. See <code>docs/ai-setup.md</code> to turn them on.</p>
	{:else}
		<form method="post" action="?/run" class={card} use:enhance={withPending((v) => (pending = v))}>
			<label class="block">
				<span class={label}>Resume to include (optional)</span>
				<select name="resumeId" class={field} disabled={pending}>
					<option value="">Profile only</option>
					{#each data.resumes as r (r.id)}
						<option value={r.id} selected={data.saved ? data.saved.resumeId === r.id : r.id === data.resumes[0].id}>{r.fileName}</option>
					{/each}
				</select>
			</label>
			<div class="mt-4 flex flex-wrap items-center gap-x-4 gap-y-2">
				<button type="submit" disabled={pending} class="{primaryButton} sm:w-auto sm:px-6">
					{pending ? 'Finding matches…' : data.saved ? 'Refresh matches' : 'Find my matches'}
				</button>
				<p class="text-sm text-ink/55 dark:text-ink/70" aria-live="polite">
					{#if pending}
						{data.ai.local
							? 'Comparing postings on a local AI model. This can take a minute or two; keep this page open.'
							: 'Comparing postings. This usually takes a few seconds.'}
					{:else if data.saved}
						Last updated {dateFmt.format(data.saved.updatedAt)}
					{/if}
				</p>
			</div>
			{#if form?.error && !pending}
				<p role="alert" class="{errorBox} mt-4">
					{form.error}
					{#if 'emptyProfile' in form}<a href="/profile" class="font-semibold underline">Complete your profile</a>{/if}
				</p>
			{/if}
		</form>
	{/if}

	{#if data.matches.length}
		<ul class="space-y-4 transition-opacity {pending ? 'opacity-50' : ''}" aria-busy={pending}>
			{#each data.matches as match (match.jobId)}
				<li class={card}>
					<div class="flex flex-wrap items-start gap-4">
						<OrgLogo name={match.job.company} domain={match.job.companyDomain} />
						<div class="min-w-0 flex-1">
							<h2 class="font-display text-xl font-semibold">
								<a href="/jobs/{match.job.id}" class="hover:text-tide hover:underline">{match.job.title}</a>
							</h2>
							<p class="text-sm text-ink/60">
								{match.job.company} · {match.job.location} ·
								{EMPLOYMENT_TYPES[match.job.employmentType as keyof typeof EMPLOYMENT_TYPES] ?? match.job.employmentType} ·
								{WORK_MODES[match.job.workMode as keyof typeof WORK_MODES] ?? match.job.workMode}
							</p>
						</div>
						<span class="rounded-full px-3 py-1 text-xs font-semibold {levels[match.level].style}">{levels[match.level].text}</span>
					</div>
					<p class="mt-4 text-ink/85">{match.reason}</p>
					{#if match.missing.length}
						<div class="mt-4">
							<h3 class="text-sm font-semibold text-ink/70">Missing for this job</h3>
							<ul class="mt-2 flex flex-wrap gap-2">
								{#each match.missing as item, i (i)}
									<li class="rounded-full bg-white/70 px-3 py-1 text-sm ring-1 ring-white dark:bg-white/10 dark:ring-white/15">{item}</li>
								{/each}
							</ul>
						</div>
					{/if}
				</li>
			{/each}
		</ul>
		<p class="text-xs text-ink/50">
			Generated by AI ({data.saved?.model}). It can be wrong or miss context, so read each posting before you apply.
		</p>
	{:else if data.saved}
		<p class={card}>No postings fit right now. Add more to your profile, or refresh when new jobs are posted.</p>
	{/if}
</div>
